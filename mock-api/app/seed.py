def _links(title: str, openlibrary: bool = True) -> dict[str, str]:
    encoded = quote(title)
    links = {"nlb": f"https://catalogue.nlb.gov.sg/search?q={encoded}"}
    if openlibrary:
        links["open_library"] = f"https://openlibrary.org/search?q={encoded}"
    return links


def _item(
    *,
    id: str,
    title: str,
    type: str,
    category: str,
    age_min: int,
    age_max: int,
    summary: str,
    tags: list[str],
    year: int,
    publisher: str,
    sensitivity: list[str] | None = None,
    popularity: int = 50,
    emoji: str = "📘",
    language: str = "English",
    openlibrary: bool = True,
) -> dict:
    return {
        "id": id,
        "title": title,
        "type": type,
        "category": category,
        "age_min": age_min,
        "age_max": age_max,
        "summary": summary,
        "tags": tags,
        "year": year,
        "publisher": publisher,
        "language": language,
        "sensitivity": sensitivity or [],
        "popularity": popularity,
        "cover_emoji": emoji,
        "external_links": _links(title, openlibrary),
    }


