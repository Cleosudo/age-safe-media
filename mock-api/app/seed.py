def build_demo_events(seed: int = 20240501) -> list[dict]:
    """Generate deterministic activity so the dashboard has something to show."""
    rng = random.Random(seed)
    now = datetime.now(timezone.utc)
    events: list[dict] = []
    children = [child for parent in DEMO_PARENTS for child in parent["children"]]
    for child in children:
        eligible = [
            item for item in CATALOGUE if item["age_min"] <= child["age"] <= item["age_max"]
        ] or CATALOGUE
        for day_offset in range(0, 45):
            day = now - timedelta(days=day_offset)
            # children are not active every day
            if rng.random() > 0.55:
                continue
            for _ in range(rng.randint(1, 3)):
                topic = rng.choice(DEMO_TOPICS)
                stamp = (day - timedelta(minutes=rng.randint(0, 600))).isoformat()
                events.append(
                    {
                        "parent_id": None,
                        "child_id": child["id"],
                        "kind": "search",
                        "topic": topic[0],
                        "item_id": None,
                        "created_at": stamp,
                    }
                )
                for _ in range(rng.randint(1, 3)):
                    item = rng.choice(CATALOGUE)
                    events.append(
                        {
                            "parent_id": None,
                            "child_id": child["id"],
                            "kind": "recommendation",
                            "topic": topic[0],
                            "item_id": item["id"],
                            "created_at": stamp,
                        }
                    )
                if rng.random() < 0.18:
                    events.append(
                        {
                            "parent_id": None,
                            "child_id": child["id"],
                            "kind": "favourite",
                            "topic": topic[0],
                            "item_id": rng.choice(eligible)["id"],
                            "created_at": stamp,
                        }
                    )
                if rng.random() < 0.28:
                    events.append(
                        {
                            "parent_id": None,
                            "child_id": child["id"],
                            "kind": "feedback_up",
                            "topic": topic[0],
                            "item_id": rng.choice(CATALOGUE)["id"],
                            "created_at": stamp,
                        }
                    )
                elif rng.random() < 0.30:
                    events.append(
                        {
                            "parent_id": None,
                            "child_id": child["id"],
                            "kind": "feedback_down",
                            "topic": topic[0],
                            "item_id": rng.choice(CATALOGUE)["id"],
                            "created_at": stamp,
                        }
                    )
    events.sort(key=lambda e: e["created_at"])
    return events
